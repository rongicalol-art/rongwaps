/**
 * Writes the two files Cloudflare reads from the built site (last step of `npm run build`):
 *
 *   dist/_headers       headers for the public files Cloudflare serves without running the server
 *                       (the server sets its own: server/respond.ts, server/content.ts)
 *   dist/.assetsignore  files that are never uploaded
 *
 * APP_ENV=staging adds the "stay away" header for search engines.
 * Usage: tsx scripts/build/siteHeaders.ts [distDir]
 */
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REVALIDATED_FILES } from '../../server/content';
import { securityHeaders } from '../../server/respond';

export function headersFile(appEnv: string | undefined): string {
  const rule = (pattern: string, headers: Record<string, string>) =>
    [pattern, ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`)].join('\n');
  return [
    '# Generated by scripts/build/siteHeaders.ts. Do not edit.',
    rule('/*', securityHeaders({ APP_ENV: appEnv })),
    // No long cache rule for /assets here: a rule applies to "not found" answers too, and a browser that
    // remembered one for a year could never load that file after a release finished rolling out. Cloudflare's
    // default (keep, but check) is cheap, and the service worker keeps these files itself (vite.config.ts).
    // The shell files are checked on every visit so a release reaches open browsers.
    ...[...REVALIDATED_FILES].map((name) => rule(`/${name}`, { 'Cache-Control': 'no-cache' })),
    // The Cloudflare address of the live site is for release checks only; search engines get the real one.
    ...(appEnv === 'production' ? [rule('https://:worker.:account.workers.dev/*', { 'X-Robots-Tag': 'noindex' })] : []),
  ].join('\n\n') + '\n';
}

export const ASSETS_IGNORE = [
  '# Generated by scripts/build/siteHeaders.ts. Do not edit.',
  '# Local-only recordings (public/audio is not in git; the live audio is on audio.ronsmandarin.com).',
  '/audio/',
  '# Cloudflare compresses for the rare browser without Brotli.',
  '*.gz',
  '*.map',
  '',
].join('\n');

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dist = path.resolve(process.argv[2] ?? 'dist');
  if (!existsSync(path.join(dist, 'index.html'))) throw new Error(`${dist} is not a built site`);
  const appEnv = process.env.APP_ENV ?? 'production';
  writeFileSync(path.join(dist, '_headers'), headersFile(appEnv));
  writeFileSync(path.join(dist, '.assetsignore'), ASSETS_IGNORE);
  console.log(`site headers: written for ${appEnv}`);
}
