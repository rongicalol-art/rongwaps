// When the teacher says each ring-cue word (`word^spot` in a talk line), from her recorded clips.
//   npx tsx scripts/audio/startHereCueTimes.ts
// Reads the clips in output/start-here-audio (made by publishStartHereAudio.ts --generate), aligns their words with
// scripts/audio/alignStartHereWords.py and writes src/screens/start-here/data/cueTimes.ts. Run it after changing a
// line that has a ring cue; the content test fails while a cue has no time.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { join } from 'node:path';
import { START_HERE_LESSONS } from '../../src/screens/start-here/data';
import { parseTalkLine, spokenWords } from '../../src/screens/start-here/data/talkParser';

const audioDir = 'output/start-here-audio';
// The alignment environment lives in the main checkout's output/ (gitignored), shared by the other audio scripts.
const python = process.env.ALIGN_PYTHON
  ?? ['output/align-venv/bin/python', join(homedir(), 'Projects/rongwaps/output/align-venv/bin/python')].find((path) => existsSync(path))
  ?? 'output/align-venv/bin/python';
const segments = new Map<string, { text: string; words: number[] }>();
for (const { screens } of START_HERE_LESSONS) for (const screen of screens) {
  for (const line of 'talk' in screen ? screen.talk ?? [] : []) for (const seg of parseTalkLine(line)) {
    if (seg.kind === 'text' && seg.cues.length) {
      segments.set(seg.clipId, { text: seg.ssml.replace(/<[^>]+>/g, ' '), words: seg.cues.map((cue) => cue.word) });
    }
  }
}

const work = mkdtempSync(join(tmpdir(), 'start-here-cues-'));
writeFileSync(join(work, 'clips.json'), JSON.stringify(Object.fromEntries([...segments].map(([id, { text }]) => [id, text]))));
const aligned = JSON.parse(execFileSync(python, ['scripts/audio/alignStartHereWords.py', join(work, 'clips.json'), audioDir],
  { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 1 << 24 })) as Record<string, [string, number][]>;

const times: Record<string, number[]> = {};
for (const [id, { text, words }] of [...segments].sort(([a], [b]) => a.localeCompare(b))) {
  const timed = aligned[id];
  const expected = spokenWords(text);
  if (!timed || timed.map(([word]) => word).join(' ') !== expected.join(' ')) throw new Error(`Clip ${id} did not align: ${text}`);
  times[id] = words.map((index) => timed[index][1]);
}

writeFileSync('src/screens/start-here/data/cueTimes.ts', `// Generated by scripts/audio/startHereCueTimes.ts. Do not edit by hand.
/** Per teacher clip: when (ms from the clip's start) she says each ring-cue word, in the order of the cues. */
export const CUE_TIMES: Record<string, number[]> = ${JSON.stringify(times, null, 2)};
`);
console.log(`Timed ${Object.keys(times).length} clips with ring cues.`);
