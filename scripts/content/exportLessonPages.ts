/**
 * Exports the public sample each lesson page shows (src/screens/lesson-page/lessonPageData.ts):
 * a few words with their recording, the lesson's grammar point names, and the page's short
 * conversation (content/lesson-pages/book-1.json) with every tappable word resolved to a
 * vocabulary entry. The packs themselves stay login-gated.
 *
 * Fails when a conversation uses a word the learner has not met by that lesson.
 * Run: npm run lesson-pages:export
 */
import { readFileSync, writeFileSync } from 'fs';

interface VocabItem { id: string; traditional: string; pinyin: string; meaning: string; simple?: string; audio: string }
interface GrammarPage { grammarNumber: number; titleEnglish: string; titleTraditional: string }
interface GrammarDoc { lessonId: number; grammarPages: GrammarPage[] }

const BOOK = 1;
const WORDS_SHOWN = 7;
const read = <T,>(file: string) => JSON.parse(readFileSync(file, 'utf8')) as T;
const vocab = read<{ items: VocabItem[] }>(`public/data/vocabulary/book-${BOOK}.json`).items;
const grammar = read<{ items: GrammarDoc[] }>(`public/data/grammar/book-${BOOK}.json`).items;
const conversations = read<Record<string, string[] | string>>(`content/lesson-pages/book-${BOOK}.json`);

const lessonOf = (id: string) => Number(id.slice(3, 5));
/** `想（要）` answers to 想 and 想要; `捷運/地鐵` to either. */
function spellings(traditional: string): string[] {
  return traditional.split('/').flatMap((form) => [form.replace(/（[^）]*）/g, ''), form.replace(/[（）]/g, '')]);
}
const audioFile = (item: VocabItem) => item.audio.replace(/^vocabulary-trimmed\/v1\//, '');
/** The measure-word note (`(M: 張 zhāng)`) belongs to the full card, not a one-line gloss. */
const gloss = (item: VocabItem) => (item.simple || item.meaning).replace(/\s*\(M: [^)]*\)/, "");
const word = (item: VocabItem, shown = item.traditional) => [shown, item.pinyin, gloss(item), audioFile(item)] as const;

function resolve(token: string, lesson: number): VocabItem {
  const [text, pin] = token.split('@');
  if (pin) {
    const pinned = vocab.find((item) => item.id === pin);
    if (!pinned || lessonOf(pinned.id) > lesson || !spellings(pinned.traditional).includes(text)) throw new Error(`Lesson ${lesson}: bad pin ${token}`);
    return pinned;
  }
  // The newest entry the learner has met: a word re-taught later carries the later meaning.
  const known = vocab.filter((item) => lessonOf(item.id) <= lesson && spellings(item.traditional).includes(text));
  const match = known.sort((a, b) => lessonOf(b.id) - lessonOf(a.id))[0];
  if (!match) throw new Error(`Lesson ${lesson}: "${text}" is not taught by this lesson (mark it =${text} if it should not be tappable)`);
  return match;
}

const PUNCTUATION = /^[，。！？、]+$/;
interface Page { wordCount: number; words: (readonly string[])[]; lines: (readonly string[] | string)[][]; grammar: (readonly string[])[] }
const pages: Record<number, Page> = {};
for (let lesson = 1; lesson <= 16; lesson++) {
  const lines = conversations[String(lesson)];
  if (!Array.isArray(lines) || lines.length !== 4) throw new Error(`Lesson ${lesson}: expected 4 conversation lines`);
  const own = vocab.filter((item) => lessonOf(item.id) === lesson);
  pages[lesson] = {
    wordCount: own.length,
    words: own.filter((item) => !/[（/]/.test(item.traditional)).slice(0, WORDS_SHOWN).map((item) => word(item)),
    lines: lines.map((line) => line.split(' ').map((token) => {
      if (PUNCTUATION.test(token)) return token;
      if (token.startsWith('=')) return token.slice(1);
      return word(resolve(token, lesson), token.split('@')[0]);
    })),
    grammar: grammar.filter((doc) => doc.lessonId === lesson).flatMap((doc) => doc.grammarPages)
      .sort((a, b) => a.grammarNumber - b.grammarNumber).map((page) => [page.titleEnglish, page.titleTraditional] as const),
  };
}

const header = `/**
 * GENERATED by scripts/content/exportLessonPages.ts (npm run lesson-pages:export). Do not edit by hand.
 * The public sample behind /books/${BOOK}/lesson-N: a few words and their recordings, grammar point names,
 * and the short conversation written for the page (content/lesson-pages/book-${BOOK}.json).
 */
import type { SampleWord } from '../landing/sampleWords';

/** A conversation line: tappable words, with plain strings for punctuation and untaught glue words. */
export type LessonPageLine = readonly (SampleWord | string)[];

export interface LessonPageData {
  /** Words the lesson teaches in total. */
  wordCount: number;
  words: readonly SampleWord[];
  lines: readonly LessonPageLine[];
  grammar: readonly (readonly [title: string, pattern: string])[];
}

export const LESSON_PAGES: Readonly<Record<number, LessonPageData>> = `;
const row = (value: unknown) => JSON.stringify(value);
const body = Object.entries(pages).map(([lesson, page]) => [
  `  ${lesson}: {`,
  `    wordCount: ${page.wordCount},`,
  `    words: [\n${page.words.map((w) => `      ${row(w)},`).join("\n")}\n    ],`,
  `    lines: [\n${page.lines.map((line) => `      [${line.map(row).join(", ")}],`).join("\n")}\n    ],`,
  `    grammar: [\n${page.grammar.map((g) => `      ${row(g)},`).join("\n")}\n    ],`,
  "  },",
].join("\n")).join("\n");
writeFileSync("src/screens/lesson-page/lessonPageData.ts", `${header}{\n${body}\n};\n`);
console.log(`lesson pages: ${Object.keys(pages).length} lessons exported`);
