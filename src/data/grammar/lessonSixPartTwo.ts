const token = (id: string, traditional: string, suffix?: string) =>
  grammarToken(id, lexicon, traditional, suffix ? { suffix } : {});

function question(
  id: string,
  number: number,
  sectionLabel: string,
  before: string,
  answer: string,
  hint: string,
  alternatives: Array<[string, string, string]>,
  feedback: [string, string],
  after = '。',
): GrammarExerciseQuestion {
  return {
    id,
    number,
    sectionLabel,
    segments: [
      ...(before ? [{ type: 'text' as const, traditional: before }] : []),
      { type: 'blank', id: `${id}-blank`, answer, hint },
      ...(after ? [{ type: 'text' as const, traditional: after }] : []),
    ],
    tiles: [
      answerTile(`${id}-correct`, answer, alternatives[0][1], alternatives[0][2]),
      ...alternatives.slice(1).map(([text, pinyin, meaning], index) =>
        answerTile(`${id}-d${index + 1}`, text, pinyin, meaning),
      ),
    ],
    correctFeedback: feedback[0],
    repairFeedback: feedback[1],
  };
}

