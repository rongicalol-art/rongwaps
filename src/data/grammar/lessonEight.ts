const token = (id: string, word: string, suffix?: string) =>
  grammarToken(id, lexicon, word, suffix ? { suffix } : {});

function question(
  id: string,
  number: number,
  label: string,
  before: string,
  answer: string,
  after: string,
  choices: Array<[string, string, string]>,
  feedback: [string, string],
): GrammarExerciseQuestion {
  return {
    id,
    number,
    sectionLabel: label,
    segments: [
      ...(before ? [{ type: 'text' as const, traditional: before }] : []),
      { type: 'blank', id: `${id}-blank`, answer, hint: feedback[1] },
      ...(after ? [{ type: 'text' as const, traditional: after }] : []),
    ],
    tiles: choices.map(([text, pinyin, meaning], index) =>
      answerTile(`${id}-${index + 1}`, text, pinyin, meaning)),
    correctFeedback: feedback[0],
    repairFeedback: feedback[1],
  };
}

